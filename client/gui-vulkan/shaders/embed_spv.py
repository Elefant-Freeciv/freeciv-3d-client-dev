#!/usr/bin/env python3
"""Embed a compiled SPIR-V module into a C header.

Usage: embed_spv.py <input.spv> <output.h> <symbol_name>

The gui-vulkan client compiles its shaders with glslc at build time and
embeds the result, so the client needs no runtime shader compiler and no
data file lookup for them.
"""

import sys


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 1

    src, dst, symbol = sys.argv[1:4]

    with open(src, "rb") as handle:
        data = handle.read()

    if len(data) % 4 != 0:
        data += b"\0" * (4 - len(data) % 4)

    guard = "FC__VK_SHADER_%s_H" % symbol.upper()

    with open(dst, "w") as out:
        out.write("/* Generated by embed_spv.py from %s. Do not edit. */\n"
                  % src.split("/")[-1])
        out.write("#ifndef %s\n#define %s\n\n" % (guard, guard))
        out.write("static const unsigned int %s[] = {\n" % symbol)
        for offset in range(0, len(data), 4):
            word = int.from_bytes(data[offset:offset + 4], "little")
            out.write("%d," % word)
            if (offset // 4) % 8 == 7:
                out.write("\n")
        out.write("\n};\n\n")
        out.write("#define %s_size ((unsigned long) sizeof(%s))\n\n"
                  % (symbol, symbol))
        out.write("#endif /* %s */\n" % guard)

    return 0


if __name__ == "__main__":
    sys.exit(main())
